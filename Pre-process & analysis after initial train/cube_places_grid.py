def plot_2d_coordinates(coords):
    # Extract x and y coordinates
    x_coords = [coord[0] for coord in coords]
    y_coords = [coord[1] for coord in coords]
    
    # Create the plot
    plt.figure(figsize=(10, 8))
    
    # Plot points
    plt.scatter(x_coords, y_coords, c='red', s=50, alpha=0.7, edgecolors='black', linewidth=0.5)
    
    # Add point labels
    for i, (x, y) in enumerate(coords):
        plt.annotate(f'P{i+1}', (x, y), xytext=(5, 5), textcoords='offset points', 
                    fontsize=10, ha='left',fontweight='bold')
    
    # Customize the plot
    plt.xlabel('X Coordinate', fontsize=12)
    plt.ylabel('Y Coordinate', fontsize=12)
    #plt.title('Plot of 30 cube positions', fontsize=14, fontweight='bold')
    plt.title('100 cube positions', fontsize=14, fontweight='bold')

    
    # Add grid
    plt.grid(True, alpha=0.3, linestyle='-', linewidth=0.5)
    plt.minorticks_on()
    plt.grid(True, which='minor', alpha=0.1, linestyle='-', linewidth=0.3)
    
    # Add x=0 and y=0 axes
    plt.axhline(y=0, color='black', linewidth=1, alpha=0.8)
    plt.axvline(x=0, color='black', linewidth=1, alpha=0.8)
    
    # Add X marker at (-0.4, 0)
    plt.plot(-0.4, 0, 'x', color='blue', markersize=12, markeredgewidth=3)
    plt.annotate('Robotic arm position', (-0.4, 0), xytext=(-5, 10), textcoords='offset points', 
                fontsize=10, ha='center', color='blue', fontweight='bold')
    
    # Set axis limits with some padding
    x_min, x_max = min(x_coords + [-0.4]), max(x_coords)
    y_min, y_max = min(y_coords), max(y_coords)
    x_padding = (x_max - x_min) * 0.1
    y_padding = (y_max - y_min) * 0.1
    
    plt.xlim(x_min - x_padding, x_max + x_padding)
    plt.ylim(y_min - y_padding, y_max + y_padding)
    
    # Make the plot look professional
    plt.tight_layout()
    
    # Show the plot
    plt.show()

# Plot the coordinates
